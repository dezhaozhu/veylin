/**
 * 项目的数据源**只能加,不能换、不能删**。
 *
 * 理由不是权限,是**历史会失真**:一个项目里前 10 条对话读的是上重,把数据源换成
 * 锅炉之后再问,那 10 条对话的结论就全对不上了 —— 而它们还在那儿,看起来像是同一
 * 个项目的连续记录。**项目的数据源是它的身份,不是一个设置项。**
 *
 * 为什么"加"不违反这条:
 * - 从"没有"到"有"是首次挂载 —— 此前没有任何靠数据得出的结论;
 * - 再加一个是**加宽** —— 原来读过的数据还在,老结论仍然成立。
 *
 * 换 / 删 / 清空才会让已有对话失真。要换 → 新建一个项目,代价很低。
 * (这和"原件不可变、快照不可变"是同一条:**能查回去**比"改起来方便"重要。)
 */
export function checkSourcesChange(
  current: readonly string[],
  next: readonly string[],
): string | null {
  const before = new Set(current);
  const removed = [...before].filter((s) => !next.includes(s));
  if (!removed.length) return null;
  return (
    `数据源只能加,不能改 —— 这个项目已经在用「${removed.join('、')}」,` +
    '之前的对话是照着它的数据得出的结论;换掉之后那些结论就和数据对不上了,' +
    '而对话还留在这个项目里。要换数据源,**新建一个项目**。'
  );
}
